WIDTH = 5
HEIGHT = 7
GAP = 1


def advance(scale):
    return (WIDTH + GAP) * scale


def measure(s, scale):
    return len(s) * advance(scale) - GAP * scale if s else 0


def draw(put, s, x, y, scale, color):
    """Calls put(x, y, w, h, color) for every lit block of every glyph."""
    for ch in s.upper():
        glyph = GLYPHS.get(ch, GLYPHS[" "])
        for gy, row in enumerate(glyph):
            for gx, cell in enumerate(row):
                if cell == "#":
                    put(x + gx * scale, y + gy * scale, scale, scale, color)
        x += advance(scale)
    return x
